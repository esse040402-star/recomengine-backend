-- Refresh persisted game vectors from the current tag-rule model without deleting other rows.
insert into public.game_trait_scores(game_id,trait_id,trait_score,score_evidence)
select g.id, r.trait_id, round(avg(r.weight),2),
       jsonb_build_object('matched_tags', jsonb_agg(distinct r.normalized_tag_name))
from public.games g
cross join lateral unnest(coalesce(g.genres,array[]::text[]) || coalesce(g.tags,array[]::text[])) as gt(tag)
join public.game_trait_tag_rules r on r.normalized_tag_name=lower(btrim(gt.tag))
group by g.id,r.trait_id
on conflict (game_id,trait_id) do update set
  trait_score=excluded.trait_score, score_evidence=excluded.score_evidence, updated_at=now();
